export function getPrettifyProfileSettingsTranslations(
  locale: NonEnglishLocale,
): Readonly<Pick<typeof en, TranslationKey>> {
  const values = VALUES[locale];
  if (values.length !== KEYS.length) {
    throw new Error(`Invalid Prettify profile Settings translations for ${locale}`);
  }
  return Object.freeze(
    Object.fromEntries(KEYS.map((key, index) => [key, values[index]])) as Pick<typeof en, TranslationKey>,
  );
}
